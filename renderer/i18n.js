let currentLang = localStorage.getItem('waveframe.lang') || 'el';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.el[key] || key;
}

function setLanguage(lang) {
  currentLang = I18N[lang] ? lang : 'el';
  localStorage.setItem('waveframe.lang', currentLang);
  applyI18n();
}

function applyI18n() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    // Preserve any child elements (e.g. icons) by only replacing text nodes
    // when the element has no element children.
    if (el.children.length === 0) {
      el.textContent = t(key);
    } else {
      const textNode = [...el.childNodes].find((n) => n.nodeType === Node.TEXT_NODE);
      if (textNode) textNode.textContent = t(key);
    }
  });
  document.dispatchEvent(new CustomEvent('waveframe:language-changed'));
}
