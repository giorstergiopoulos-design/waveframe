/* Windows' Chromium/Electron does not render Unicode regional-indicator flag
   emoji as pictures (shows literal two-letter codes instead) — draw real
   SVG flags inline instead so they render consistently on every Windows box. */
function svgTag(inner) { return `<svg viewBox="0 0 30 20" xmlns="http://www.w3.org/2000/svg">${inner}</svg>`; }
function flagStripesH(colors) {
  const h = 20 / colors.length;
  return svgTag(colors.map((c, i) => `<rect y="${(i * h).toFixed(2)}" width="30" height="${(h + 0.1).toFixed(2)}" fill="${c}"/>`).join(''));
}
function flagStripesV(colors) {
  const w = 30 / colors.length;
  return svgTag(colors.map((c, i) => `<rect x="${(i * w).toFixed(2)}" width="${(w + 0.1).toFixed(2)}" height="20" fill="${c}"/>`).join(''));
}
function flagNordicCross(bg, cross) {
  return svgTag(`<rect width="30" height="20" fill="${bg}"/><rect x="9" width="4" height="20" fill="${cross}"/><rect y="8" width="30" height="4" fill="${cross}"/>`);
}
